<?php
/**
 * Renders the `[doublescale_booking]` shortcode.
 *
 * The shortcode does not render the booking form inline — it embeds the
 * standalone booking page that {@see BookingFrontendHandler} already serves at
 * `?doublescale_booking_event=<slug>`, so the shortcode, the Direct Link, the
 * Embed Code and the QR Code in the admin Share modal all resolve to one route.
 *
 * @package DoubleScale
 */

namespace DoubleScale\Modules\Booking\Renderer;

defined( 'ABSPATH' ) || exit;

use DoubleScale\Modules\Booking\Models\EventModel;

/**
 * Booking shortcode handler.
 */
class BookingShortcode {

	/**
	 * Shortcode tag. Matches the tag generated by the admin Share modal.
	 *
	 * @var string
	 */
	public const SHORTCODE_NAME = 'doublescale_booking';

	/**
	 * @var string
	 */
	private const SHORTCODE = self::SHORTCODE_NAME;

	/**
	 * Fallback minimum height when neither `min_height` nor `height` is given.
	 *
	 * @var string
	 */
	private const DEFAULT_MIN_HEIGHT = '480px';

	/**
	 * Event model class name (injectable for tests).
	 *
	 * @var string
	 */
	private string $event_model_class;

	/**
	 * @param string $event_model_class Event model class name.
	 */
	public function __construct( string $event_model_class = EventModel::class ) {
		$this->event_model_class = $event_model_class;

		add_shortcode( self::SHORTCODE, array( $this, 'render_shortcode' ) );
		add_action( 'wp_enqueue_scripts', array( $this, 'enqueue_iframe_assets' ) );
	}

	/**
	 * Styles for the host page that embeds the booking iframe via shortcode.
	 */
	public function enqueue_iframe_assets(): void {
		if ( is_admin() ) {
			return;
		}

		$post = get_post();
		$content = $post ? (string) $post->post_content : '';
		$has_booking = $content
			&& (
				has_shortcode( $content, self::SHORTCODE )
				|| false !== strpos( $content, self::SHORTCODE )
				|| false !== strpos( $content, 'doublescale-booking' )
			);

		// Page builders may store the shortcode outside raw post_content; still
		// enqueue lightly so any iframe on the page is sized correctly.
		if ( ! $has_booking && ! is_singular() ) {
			return;
		}

		$version = defined( 'DOUBLESCALE_VERSION' ) ? \DOUBLESCALE_VERSION : '1.0.0';
		$handle  = 'doublescale-booking-iframe';
		wp_register_style( $handle, false, array(), $version );
		wp_enqueue_style( $handle );
		wp_add_inline_style(
			$handle,
			'.doublescale-booking-iframe{display:block!important;width:100%!important;max-width:100%!important;margin:0 auto!important;border:0!important;background:transparent!important;box-sizing:border-box!important;vertical-align:top;overflow:hidden;}'
			. '.entry-content .doublescale-booking-iframe,.wp-block-group .doublescale-booking-iframe,.eb-parent .doublescale-booking-iframe,.wp-block-kadence-column .doublescale-booking-iframe{width:100%!important;max-width:100%!important;}'
			. '.doublescale-booking-iframe-wrap{display:block;width:100%;max-width:100%;margin:0;padding:0;line-height:0;}'
		);

		wp_register_script( $handle, false, array(), $version, true );
		wp_enqueue_script( $handle );
		wp_add_inline_script(
			$handle,
			"(function(){function size(iframe,h){if(!iframe||!h||h<200){return;}var next=Math.ceil(h);iframe.style.height=next+'px';iframe.style.minHeight=next+'px';iframe.style.maxHeight='none';}function bind(iframe){if(!iframe||iframe.dataset.dsBound){return;}iframe.dataset.dsBound='1';window.addEventListener('message',function(e){if(!e||!e.data||e.data.type!=='doublescale-booking-resize'){return;}if(e.source!==iframe.contentWindow){return;}size(iframe,parseInt(e.data.height,10));});iframe.addEventListener('load',function(){try{iframe.contentWindow.postMessage({type:'doublescale-booking-request-height'},'*');}catch(err){}});}function scan(){document.querySelectorAll('iframe.doublescale-booking-iframe').forEach(bind);}scan();document.addEventListener('DOMContentLoaded',scan);window.addEventListener('load',scan);if(typeof MutationObserver!=='undefined'){new MutationObserver(scan).observe(document.documentElement,{childList:true,subtree:true});}})();"
		);
	}

	/**
	 * Render the shortcode.
	 *
	 * @param array<string, string>|string $atts Shortcode attributes.
	 * @return string
	 */
	public function render_shortcode( $atts ): string {
		$atts = shortcode_atts(
			array(
				'id'         => null,
				'width'      => '100%',
				'min_height' => null,
				'max_height' => null,
				'height'     => null,
			),
			(array) $atts,
			self::SHORTCODE
		);

		$id = (int) $atts['id'];
		if ( $id <= 0 ) {
			return esc_html__( 'Invalid event ID.', 'doublescale' );
		}

		$event = $this->event_model_class::find( $id );
		if ( ! $event || empty( $event->slug ) ) {
			return esc_html__( 'Event not found.', 'doublescale' );
		}

		list( $width, $min_height, $max_height ) = $this->parse_dimensions( $atts );

		$src = add_query_arg(
			array(
				'doublescale_booking_event' => (string) $event->slug,
				'embed'                     => '1',
			),
			home_url( '/' )
		);

		return sprintf(
			'<div class="doublescale-booking-iframe-wrap"><iframe class="doublescale-booking-iframe" src="%s" title="%s" loading="eager" style="border:0;display:block;width:%s;min-height:%s;max-height:%s;background:transparent;"></iframe></div>',
			esc_url( $src ),
			esc_attr__( 'Booking form', 'doublescale' ),
			esc_attr( $width ),
			esc_attr( $min_height ),
			esc_attr( $max_height )
		);
	}

	/**
	 * Resolve the width / min-height / max-height CSS values.
	 *
	 * `height` is a legacy alias honoured only when `min_height` is absent.
	 * A width of `auto` collapses an iframe to its intrinsic 300px, so it is
	 * treated as "full width" instead.
	 *
	 * @param array<string, string|null> $atts Parsed shortcode attributes.
	 * @return array{0: string, 1: string, 2: string}
	 */
	private function parse_dimensions( array $atts ): array {
		$width = $this->sanitize_dimension( $atts['width'], '100%' );
		if ( 'auto' === strtolower( $width ) ) {
			$width = '100%';
		}

		$min_height = $this->sanitize_dimension( $atts['min_height'], '' );
		if ( '' === $min_height ) {
			$min_height = $this->sanitize_dimension( $atts['height'], self::DEFAULT_MIN_HEIGHT );
		}

		$max_height = $this->sanitize_dimension( $atts['max_height'], 'auto' );

		return array( $width, $min_height, $max_height );
	}

	/**
	 * Validate a CSS length so shortcode attributes cannot inject declarations
	 * into the inline `style`. Bare numbers are treated as pixels.
	 *
	 * @param string|null $value    Raw attribute value.
	 * @param string      $fallback Value used when $value is empty or invalid.
	 * @return string
	 */
	private function sanitize_dimension( $value, string $fallback ): string {
		$value = trim( (string) $value );

		if ( '' === $value ) {
			return $fallback;
		}

		if ( preg_match( '/^auto$/i', $value ) ) {
			return 'auto';
		}

		if ( preg_match( '/^(\d+(?:\.\d+)?)(px|%|em|rem|vh|vw)?$/i', $value, $matches ) ) {
			$unit = isset( $matches[2] ) && '' !== $matches[2] ? strtolower( $matches[2] ) : 'px';
			return $matches[1] . $unit;
		}

		return $fallback;
	}
}
