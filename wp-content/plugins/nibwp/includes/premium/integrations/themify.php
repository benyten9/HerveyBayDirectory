/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_move_module(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $rows = $resolved['rows'];
    $located = nibwp_themify_locate_module($rows, $input);

    if ($located instanceof WP_Error) {
        return $located;
    }

    $module = $located['element'];
    $destination = nibwp_themify_locate_column($rows, $input, 'to_element_id', 'to_row', 'to_column');

    if ($destination instanceof WP_Error) {
        return $destination;
    }

    // Moving a sub-row into one of its own columns would make the page a cycle
    // that the renderer walks forever.
    if (nibwp_themify_is_subrow($module)
        && count($destination['path']) > count($located['path'])
        && array_slice($destination['path'], 0, count($located['path'])) === $located['path']) {
        return nibwp_themify_err('move_into_self', __('A sub-row cannot be moved inside itself.', 'nibwp'));
    }

    if (!nibwp_themify_remove_at($rows, $located['path'])) {
        return nibwp_themify_err('move_failed', __('That module could not be moved.', 'nibwp'), 500);
    }

    // The removal re-keyed the list the module came out of, so the destination
    // column has to be found again by its id rather than by the path recorded
    // before the removal.
    $destination_id = nibwp_themify_element_id($destination['element']);
    $to_path = $destination_id === '' ? $destination['path'] : nibwp_themify_find_path($rows, $destination_id);

    if ($to_path === null) {
        return nibwp_themify_err('move_failed', __('The destination column could not be found after the move.', 'nibwp'), 500);
    }

    $column = nibwp_themify_at($rows, $to_path);

    if ($column === null) {
        return nibwp_themify_err('move_failed', __('The destination column could not be found after the move.', 'nibwp'), 500);
    }

    $list = nibwp_themify_modules($column);
    $position = nibwp_themify_int($input['to_index'] ?? null);
    $at = $position === null ? count($list) : max(0, min($position, count($list)));
    array_splice($list, $at, 0, [$module]);
    $column['modules'] = $list;

    if (!nibwp_themify_replace_at($rows, $to_path, $column)) {
        return nibwp_themify_err('move_failed', __('That module could not be moved.', 'nibwp'), 500);
    }

    $written = nibwp_themify_write((int) $resolved['post']->ID, $rows);

    if ($written instanceof WP_Error) {
        return $written;
    }

    return $written + [
        'element_id' => nibwp_themify_element_id($module),
        'to_column' => $destination_id,
        'to_index' => $at,
    ];
}

