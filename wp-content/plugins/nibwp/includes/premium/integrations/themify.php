/**
 * Integration: Themify Builder 7.8.2.
 *
 * THE BUILDER DATA, because everything here turns on it.
 *
 * A page's builder content lives in one post meta row, key
 * `_themify_builder_settings_json` (ThemifyBuilder_Data_Manager::META_KEY,
 * classes/class-builder-data-manager.php:28). The value is a JSON STRING, not a
 * serialised array — encoded with JSON_UNESCAPED_UNICODE|JSON_UNESCAPED_SLASHES
 * (class-builder-data-manager.php:284-286) and written straight into
 * $wpdb->postmeta by the plugin (class-builder-data-manager.php:502-532), which
 * is why a plain get_post_meta() hands back a string.
 *
 * There is a SECOND, older meta: `_themify_builder_settings`
 * (LEGACY_META_KEY, class-builder-data-manager.php:31), holding the same tree as
 * serialised PHP. It is not a mirror and not a cache — it is the pre-7.x format,
 * and the plugin migrates it to JSON the first time it reads a page that still
 * has one, then deletes it (class-builder-data-manager.php:72-76 and :543). A
 * page carrying it is a page paying a write on every cold read, which the audit
 * reports. Reads here accept either, writes only ever produce JSON.
 *
 * The decoded shape is a LIST OF ROWS, each row holding columns, each column
 * holding modules. The canonical minimal form is spelled out literally by the
 * plugin itself at classes/class-themify-global-styles.php:278:
 *
 *   [ { "element_id": "row<id>",
 *       "styling":    { ...row settings... },
 *       "cols": [ { "element_id":  "col<id>",
 *                   "grid_class":  "col-full",
 *                   "styling":     { ...column settings... },
 *                   "modules": [ { "element_id":   "mod<id>",
 *                                  "mod_name":     "text",
 *                                  "mod_settings": { ...module settings... } } ] } ] } ]
 *
 * Four things catch people out:
 *   - a ROW keeps its settings under `styling`; a MODULE keeps them under
 *     `mod_settings`. Same idea, two key names, and the display-condition reader
 *     looks in both (class-themify-builder-display-conditions.php:50).
 *   - a module may itself be a SUB-ROW: when a module carries `cols`, those
 *     columns hold modules of their own and the module's settings move to
 *     `styling` rather than `mod_settings`
 *     (class-themify-builder-model.php:915-945, :987). Nesting stops there —
 *     the plugin's own walkers go exactly two levels deep.
 *   - every row, column and module carries an `element_id`, a short unique
 *     string generated by the plugin (class-themify-builder-model.php:1003-1035).
 *     That is the identity of a module instance. Index position is not: it
 *     changes the moment a row moves.
 *   - the writer DISCARDS the whole payload if the encoded JSON contains neither
 *     the word `modules` nor `styling` (class-builder-data-manager.php:471-473).
 *     A structure that looks plausible but trips that check saves as an empty
 *     page.
 *
 * WHY WRITES GO THROUGH THE PLUGIN AND NEVER TOUCH THE META DIRECTLY.
 *
 * Persisting builder data correctly is not "json_encode and update_post_meta".
 * ThemifyBuilder_Data_Manager::save_data() (class-builder-data-manager.php:94)
 * runs a recursive escaper that re-decodes nested JSON strings, applies
 * wp_kses_post to every string for anyone without `unfiltered_html`, and
 * sanitises the module settings that end up in inline CSS
 * (class-builder-data-manager.php:169-247); generates any missing element ids
 * (:475-478); rewrites the plain-text mirror inside post_content between
 * `<!--themify_builder_static-->` markers (:368-394); records a revision; stores
 * which global styles the page uses (:120); and runs the whole thing inside a
 * database transaction. Skip any one of those and the page renders empty, loses
 * a module's content, or saves with duplicate element ids that the editor then
 * cannot address. So every write here builds the finished rows array and hands
 * it to save_data(), exactly as the plugin's own programmatic writer does
 * (includes/plugin-compat/wpml-translation.php:102-111).
 *
 * STRUCTURE IS OURS, CONTENT IS NOT. The transforms move rows, columns and
 * modules around and edit named settings. Every key they do not understand is
 * copied through untouched, because an unrecognised key is far more likely to
 * belong to a newer Builder, a Builder add-on or a third-party module than to be
 * junk, and dropping it destroys the page it came from. A test pins that with a
 * fixture full of keys this file has never heard of.
 *
 * SECRETS: the plugin's own settings option is reported through an allow-list.
 * `themify_builder_setting` is a flat bag that add-ons write into, including
 * licence keys, so anything not vouched for comes back as a name and whether it
 * is set, and never as a value.
 */

/** Reading or editing one page's builder data is gated per-post, never site-wide. */
const NIBWP_THEMIFY_POST_CAP = 'edit_post';

/** Browsing the builder's own libraries needs authorship somewhere on the site. */
const NIBWP_THEMIFY_AUTHOR_CAP = 'edit_posts';

/** Builder settings change every page for every author. */
const NIBWP_THEMIFY_ADMIN_CAP = 'manage_options';

/** The current builder meta key: a JSON string. */
const NIBWP_THEMIFY_META = '_themify_builder_settings_json';

/** The pre-7.x builder meta key: serialised PHP, migrated on read by the plugin. */
const NIBWP_THEMIFY_LEGACY_META = '_themify_builder_settings';

/** The option holding the builder's own configuration. */
const NIBWP_THEMIFY_OPTION = 'themify_builder_setting';

/** Themify's reusable-layout post type. */
const NIBWP_THEMIFY_LAYOUT_CPT = 'tbuilder_layout';

/** Themify's layout-part post type. */
const NIBWP_THEMIFY_LAYOUT_PART_CPT = 'tbuilder_layout_part';

/** Themify's global-style post type. */
const NIBWP_THEMIFY_GLOBAL_STYLE_CPT = 'tglobal_style';

/** The marker pair wrapping the plain-text mirror Themify keeps in post_content. */
const NIBWP_THEMIFY_STATIC_OPEN = '<!--themify_builder_static-->';

/** How many rows any listing returns, whatever was asked for. */
const NIBWP_THEMIFY_MAX_ROWS = 200;

/** What a listing returns when no limit was given. */
const NIBWP_THEMIFY_DEFAULT_ROWS = 50;

/**
 * Is Themify Builder actually loaded?
 *
 * THEMIFY_BUILDER_DIR is defined by the plugin's bootstrap before anything else
 * (themify-builder.php:202) and Themify_Builder is the class the rest of it hangs
 * off (classes/class-themify-builder.php:11), so between them they separate "not
 * installed" from "installed and half-booted". THEMIFY_VERSION is deliberately
 * not the probe: a Themify theme defines it too, with no builder behind it.
 */
function nibwp_themify_guard(): ?WP_Error
{
    if (!defined('THEMIFY_BUILDER_DIR') && !class_exists('Themify_Builder')) {
        return new WP_Error(
            'nibwp_themify_missing',
            __('Themify Builder is not active on this site.', 'nibwp'),
            ['status' => 400]
        );
    }

    return null;
}

/** A refusal about the request itself. */
function nibwp_themify_err(string $code, string $message, int $status = 400): WP_Error
{
    return new WP_Error('nibwp_themify_' . $code, $message, ['status' => $status]);
}

/** A refusal about authority over one page. */
function nibwp_themify_post_forbidden(int $post_id): WP_Error
{
    return new WP_Error(
        'nibwp_themify_post_forbidden',
        sprintf(
            /* translators: 1: post ID, 2: capability name */
            __('This account cannot edit post %1$d: the %2$s capability for that post is missing.', 'nibwp'),
            $post_id,
            NIBWP_THEMIFY_POST_CAP
        ),
        ['status' => 403]
    );
}

/** A refusal about authority to browse the builder's libraries at all. */
function nibwp_themify_author_forbidden(string $what): WP_Error
{
    return new WP_Error(
        'nibwp_themify_author_forbidden',
        sprintf(
            /* translators: 1: what was being attempted, 2: capability name */
            __('%1$s needs the %2$s capability, which this account does not have.', 'nibwp'),
            $what,
            NIBWP_THEMIFY_AUTHOR_CAP
        ),
        ['status' => 403]
    );
}

/** A refusal about authority over the whole site's builder configuration. */
function nibwp_themify_forbidden(string $what): WP_Error
{
    return new WP_Error(
        'nibwp_themify_forbidden',
        sprintf(
            /* translators: 1: what was being attempted, 2: capability name */
            __('%1$s needs the %2$s capability, which this account does not have.', 'nibwp'),
            $what,
            NIBWP_THEMIFY_ADMIN_CAP
        ),
        ['status' => 403]
    );
}

/** The author-level gate, for the builder's shared libraries. */
function nibwp_themify_require_author(string $what): ?WP_Error
{
    return current_user_can(NIBWP_THEMIFY_AUTHOR_CAP) ? null : nibwp_themify_author_forbidden($what);
}

/** The site-wide gate, for the builder's own configuration only. */
function nibwp_themify_require_admin(string $what): ?WP_Error
{
    return current_user_can(NIBWP_THEMIFY_ADMIN_CAP) ? null : nibwp_themify_forbidden($what);
}

/**
 * The stored builder rows for a post, or null when there are none.
 *
 * WHY THIS DOES NOT CALL THE PLUGIN'S OWN READER.
 * ThemifyBuilder_Data_Manager::get_data() migrates a legacy row to JSON as a
 * SIDE EFFECT of reading it (class-builder-data-manager.php:61-76) — it writes.
 * A listing that walks two hundred posts would quietly rewrite the lot, so
 * reading is done here and migration is left to the plugin, where the owner can
 * see it happen.
 *
 * The JSON key holds a string, so it is json_decode()d. The legacy key holds
 * serialised PHP, and WordPress's own get_post_meta() has already run it through
 * maybe_unserialize() before it reaches here; the extra maybe_unserialize() below
 * is for the double-serialised rows older imports leave behind. Nothing here
 * calls unserialize() on anything, and a test parses this file to prove it.
 *
 * @return list<array<string, mixed>>|null
 */
function nibwp_themify_read_builder(int $post_id): ?array
{
    $raw = get_post_meta($post_id, NIBWP_THEMIFY_META, true);

    if (is_string($raw) && $raw !== '') {
        $decoded = json_decode($raw, true);

        return is_array($decoded) && $decoded !== [] ? nibwp_themify_rows($decoded) : null;
    }

    // A row written by an importer can already be an array by the time it gets
    // here; the plugin handles that case too (class-builder-data-manager.php:56).
    if (is_array($raw) && $raw !== []) {
        return nibwp_themify_rows($raw);
    }

    $legacy = get_post_meta($post_id, NIBWP_THEMIFY_LEGACY_META, true);

    if ($legacy === '' || $legacy === null || $legacy === false) {
        return null;
    }

    $legacy = maybe_unserialize($legacy);

    if (is_string($legacy)) {
        $legacy = json_decode($legacy, true);
    }

    return is_array($legacy) && $legacy !== [] ? nibwp_themify_rows($legacy) : null;
}

/**
 * Re-key the row list without touching anything inside a row.
 *
 * A sparse list would make the row indexes a caller is handed mean something
 * different from the positions a later write produces. Only the outer list is
 * re-keyed; every key inside each row is left exactly where it was.
 *
 * @param array<mixed> $data
 * @return list<array<string, mixed>>
 */
function nibwp_themify_rows(array $data): array
{
    $rows = [];

    foreach (array_values($data) as $row) {
        if (is_array($row)) {
            $rows[] = $row;
        }
    }

    return $rows;
}

/** Is this element a sub-row — a module that holds columns of its own? */
function nibwp_themify_is_subrow(array $element): bool
{
    return isset($element['cols']) && is_array($element['cols']) && $element['cols'] !== [];
}

/**
 * Where an element keeps its settings.
 *
 * Rows and sub-rows use `styling`, plain modules use `mod_settings`. The
 * display-condition reader checks both in that order
 * (class-themify-builder-display-conditions.php:50), so this does too.
 */
function nibwp_themify_settings_key(array $element): string
{
    if (isset($element['mod_settings']) && is_array($element['mod_settings'])) {
        return 'mod_settings';
    }

    if (isset($element['styling']) && is_array($element['styling'])) {
        return 'styling';
    }

    return nibwp_themify_is_subrow($element) || !isset($element['mod_name']) ? 'styling' : 'mod_settings';
}

/**
 * An element's settings, whichever key this element keeps them under.
 *
 * @return array<string, mixed>
 */
function nibwp_themify_settings(array $element): array
{
    $key = nibwp_themify_settings_key($element);

    return isset($element[$key]) && is_array($element[$key]) ? $element[$key] : [];
}

/** An element's id, '' when the stored data does not carry one. */
function nibwp_themify_element_id(array $element): string
{
    return isset($element['element_id']) && is_scalar($element['element_id'])
        ? (string) $element['element_id']
        : '';
}

/** A module's type, '' for rows and columns. */
function nibwp_themify_mod_name(array $element): string
{
    return isset($element['mod_name']) && is_scalar($element['mod_name'])
        ? (string) $element['mod_name']
        : '';
}

/** Clamp a caller's row count to something a response can carry. */
function nibwp_themify_limit(mixed $raw): int
{
    if ($raw === null || $raw === '') {
        return NIBWP_THEMIFY_DEFAULT_ROWS;
    }

    $limit = is_scalar($raw) ? (int) $raw : NIBWP_THEMIFY_DEFAULT_ROWS;

    if ($limit < 1) {
        return NIBWP_THEMIFY_DEFAULT_ROWS;
    }

    return min($limit, NIBWP_THEMIFY_MAX_ROWS);
}

/** A caller's integer, or null when they did not give one. */
function nibwp_themify_int(mixed $raw): ?int
{
    return is_scalar($raw) && $raw !== '' && $raw !== true && $raw !== false ? (int) $raw : null;
}

/**
 * Resolve a caller's post id claim into builder data we are allowed to work on.
 *
 * ORDER MATTERS AND IS DELIBERATE. The capability answers FIRST, before anything
 * that could reveal whether the id exists or carries builder data: otherwise an
 * unauthorised caller walks the id space and learns the site's contents from the
 * shape of the refusals. `edit_post` with the id bound into it, never
 * `edit_posts` — the question is whether this account may edit THIS page — and
 * on a missing id core's map_meta_cap refuses it anyway, so nothing fatals.
 *
 * Only once authority is settled do existence and "is this actually a builder
 * page" get answered, each with its own code so a caller can tell them apart.
 *
 * @return array{post: object, rows: list<array<string, mixed>>}|WP_Error
 */
function nibwp_themify_resolve(mixed $raw_id): array|WP_Error
{
    $post_id = is_scalar($raw_id) ? (int) $raw_id : 0;

    if ($post_id <= 0) {
        return nibwp_themify_err('bad_post_id', __('A post_id is required.', 'nibwp'));
    }

    if (!current_user_can(NIBWP_THEMIFY_POST_CAP, $post_id)) {
        return nibwp_themify_post_forbidden($post_id);
    }

    $post = get_post($post_id);

    if (!is_object($post) || !isset($post->ID)) {
        return nibwp_themify_err(
            'post_not_found',
            sprintf(
                /* translators: %d: post ID */
                __('No post %d exists.', 'nibwp'),
                $post_id
            ),
            404
        );
    }

    $rows = nibwp_themify_read_builder($post_id);

    if ($rows === null) {
        return nibwp_themify_err(
            'no_builder_data',
            sprintf(
                /* translators: %d: post ID */
                __('Post %d has no Themify Builder data; its content is plain editor content.', 'nibwp'),
                $post_id
            ),
            404
        );
    }

    return ['post' => $post, 'rows' => $rows];
}

/* ------------------------------------------------- walking the row structure */

/**
 * The path to an element, by its id, anywhere in the tree.
 *
 * A path is the list of array keys that reaches the element, so
 * [0, 'cols', 1, 'modules', 2] is the third module of the second column of the
 * first row. Addressing by id rather than by position is what makes an edit
 * survive someone else moving a row.
 *
 * @param list<array<string, mixed>> $rows
 * @return list<int|string>|null
 */
function nibwp_themify_find_path(array $rows, string $element_id): ?array
{
    if ($element_id === '') {
        return null;
    }

    foreach ($rows as $ri => $row) {
        if (!is_array($row)) {
            continue;
        }

        if (nibwp_themify_element_id($row) === $element_id) {
            return [$ri];
        }

        $found = nibwp_themify_find_in_cols($row, $element_id, [$ri]);

        if ($found !== null) {
            return $found;
        }
    }

    return null;
}

/**
 * The same search, one container deep. Split out because a sub-row is a module
 * that holds columns, so the walk is the same shape twice.
 *
 * @param array<string, mixed> $container
 * @param list<int|string> $prefix
 * @return list<int|string>|null
 */
function nibwp_themify_find_in_cols(array $container, string $element_id, array $prefix): ?array
{
    if (!isset($container['cols']) || !is_array($container['cols'])) {
        return null;
    }

    foreach ($container['cols'] as $ci => $col) {
        if (!is_array($col)) {
            continue;
        }

        $col_path = array_merge($prefix, ['cols', $ci]);

        if (nibwp_themify_element_id($col) === $element_id) {
            return $col_path;
        }

        if (!isset($col['modules']) || !is_array($col['modules'])) {
            continue;
        }

        foreach ($col['modules'] as $mi => $module) {
            if (!is_array($module)) {
                continue;
            }

            $mod_path = array_merge($col_path, ['modules', $mi]);

            if (nibwp_themify_element_id($module) === $element_id) {
                return $mod_path;
            }

            // A sub-row's own columns. The plugin's walkers stop here and so
            // does this one (class-themify-builder-model.php:1018-1029).
            $deeper = nibwp_themify_find_sub($module, $element_id, $mod_path);

            if ($deeper !== null) {
                return $deeper;
            }
        }
    }

    return null;
}

/**
 * @param array<string, mixed> $module
 * @param list<int|string> $prefix
 * @return list<int|string>|null
 */
function nibwp_themify_find_sub(array $module, string $element_id, array $prefix): ?array
{
    if (!isset($module['cols']) || !is_array($module['cols'])) {
        return null;
    }

    foreach ($module['cols'] as $ci => $col) {
        if (!is_array($col)) {
            continue;
        }

        $col_path = array_merge($prefix, ['cols', $ci]);

        if (nibwp_themify_element_id($col) === $element_id) {
            return $col_path;
        }

        if (!isset($col['modules']) || !is_array($col['modules'])) {
            continue;
        }

        foreach ($col['modules'] as $mi => $sub) {
            if (is_array($sub) && nibwp_themify_element_id($sub) === $element_id) {
                return array_merge($col_path, ['modules', $mi]);
            }
        }
    }

    return null;
}

/**
 * The element at a path, or null.
 *
 * @param list<array<string, mixed>> $rows
 * @param list<int|string> $path
 * @return array<string, mixed>|null
 */
function nibwp_themify_at(array $rows, array $path): ?array
{
    $cursor = $rows;

    foreach ($path as $key) {
        if (!is_array($cursor) || !array_key_exists($key, $cursor)) {
            return null;
        }

        $cursor = $cursor[$key];
    }

    return is_array($cursor) ? $cursor : null;
}

/**
 * Replace the element at a path, leaving every other key in the tree alone.
 *
 * @param list<array<string, mixed>> $rows
 * @param list<int|string> $path
 * @param array<string, mixed> $value
 */
function nibwp_themify_replace_at(array &$rows, array $path, array $value): bool
{
    $cursor = &$rows;

    foreach ($path as $key) {
        if (!is_array($cursor) || !array_key_exists($key, $cursor)) {
            return false;
        }

        $cursor = &$cursor[$key];
    }

    $cursor = $value;

    return true;
}

/**
 * Remove the element at a path and re-key the list it came out of.
 *
 * @param list<array<string, mixed>> $rows
 * @param list<int|string> $path
 */
function nibwp_themify_remove_at(array &$rows, array $path): bool
{
    if ($path === []) {
        return false;
    }

    $last = $path[count($path) - 1];
    $parent_path = array_slice($path, 0, -1);
    $cursor = &$rows;

    foreach ($parent_path as $key) {
        if (!is_array($cursor) || !array_key_exists($key, $cursor)) {
            return false;
        }

        $cursor = &$cursor[$key];
    }

    if (!is_array($cursor) || !array_key_exists($last, $cursor)) {
        return false;
    }

    unset($cursor[$last]);
    // Only the list the element came out of is re-keyed. A gap in a module list
    // is a position that no longer means what the next read says it means.
    $cursor = array_values($cursor);

    return true;
}

/**
 * Insert an element into the list at a path, at a position.
 *
 * @param list<array<string, mixed>> $rows
 * @param list<int|string> $list_path
 * @param array<string, mixed> $value
 */
function nibwp_themify_insert_at(array &$rows, array $list_path, array $value, ?int $position): bool
{
    $cursor = &$rows;

    foreach ($list_path as $key) {
        if (!is_array($cursor) || !array_key_exists($key, $cursor)) {
            return false;
        }

        $cursor = &$cursor[$key];
    }

    if (!is_array($cursor)) {
        return false;
    }

    $list = array_values($cursor);
    $at = $position === null ? count($list) : max(0, min($position, count($list)));
    array_splice($list, $at, 0, [$value]);
    $cursor = $list;

    return true;
}

/**
 * A fresh element id, from the plugin's own generator when it is reachable.
 *
 * The plugin checks a candidate against the ids already in the page
 * (class-themify-builder-model.php:1003-1005), which is the part that matters:
 * two elements sharing an id is a page the editor cannot address. When the
 * generator is not reachable the fallback is a long random string, and the
 * caller checks it against the page before using it.
 */
function nibwp_themify_new_id(string $prefix): string
{
    if (class_exists('Themify_Builder_Model') && method_exists('Themify_Builder_Model', 'generateID')) {
        try {
            $generated = Themify_Builder_Model::generateID();

            if (is_scalar($generated) && (string) $generated !== '') {
                return (string) $generated;
            }
        } catch (\Throwable $error) {
            // Fall through to the local generator.
        }
    }

    return $prefix . substr(str_replace('.', '', uniqid('', true)), -12);
}

/**
 * A fresh id that is definitely not already in this page.
 *
 * @param list<array<string, mixed>> $rows
 */
function nibwp_themify_unique_id(array $rows, string $prefix): string
{
    for ($attempt = 0; $attempt < 20; $attempt++) {
        $candidate = nibwp_themify_new_id($prefix);

        if (nibwp_themify_find_path($rows, $candidate) === null) {
            return $candidate;
        }
    }

    return $prefix . substr(str_replace('.', '', uniqid('', true)), -12) . (string) count($rows);
}

/* ----------------------------------------------------------- module registry */

/**
 * Module types this site can actually render, as name => source.
 *
 * Themify_Builder_Model::get_modules('active') is the registry: the built-in
 * list plus whatever add-ons registered, minus anything switched off in the
 * builder settings (class-themify-builder-model.php:492-561). It returns
 * name => directory (or true for a built-in) and does NOT include a file, which
 * is why this is the probe rather than load_modules() — that one requires every
 * module file.
 *
 * @return array<string, bool>
 */
function nibwp_themify_module_registry(string $type = 'active'): array
{
    if (!class_exists('Themify_Builder_Model') || !method_exists('Themify_Builder_Model', 'get_modules')) {
        return [];
    }

    try {
        $modules = Themify_Builder_Model::get_modules($type);
    } catch (\Throwable $error) {
        return [];
    }

    if (!is_array($modules)) {
        return [];
    }

    $out = [];

    foreach ($modules as $name => $source) {
        $out[(string) $name] = true;
    }

    return $out;
}

/** Is this module type registered on this site right now? */
function nibwp_themify_module_registered(string $mod_name, ?array $registry = null): bool
{
    if ($mod_name === '') {
        return false;
    }

    $registry ??= nibwp_themify_module_registry('all');

    return isset($registry[$mod_name]);
}

/* -------------------------------------------------------------- the write seam */

/**
 * Can this build persist builder data at all?
 *
 * save_data() is the only sanitised seam. Without it there is nothing safe to
 * borrow, and hand-rolling the escaper, the kses floor, the element-id generator
 * and the static-content mirror is how a page ends up rendering nothing.
 */
function nibwp_themify_can_write(): bool
{
    return class_exists('ThemifyBuilder_Data_Manager')
        && method_exists('ThemifyBuilder_Data_Manager', 'save_data');
}

/**
 * Persist transformed rows and invalidate what a reader would otherwise see.
 *
 * THE CACHES, AND WHO CLEARS WHICH.
 *
 * save_data() -> update_builder_meta() already clears the ones tied to the meta
 * row: update_meta_cache(), wp_cache_delete() for both posts and post_meta,
 * clean_post_cache(), TFCache::remove_cache($post_id) — Themify's own rendered
 * HTML cache, which serves a cached page file and would otherwise keep showing
 * the pre-write content — themify_clear_menu_cache(), and
 * TFCache::clear_3rd_plugins_cache() for whichever page cache the site runs
 * (class-builder-data-manager.php:544-550).
 *
 * It does NOT delete the per-post generated CSS file. Themify writes each
 * builder page's styling to its own stylesheet under uploads, and that file is
 * keyed by post id, so after a write it still holds the old rules and the page
 * renders new markup with stale CSS. THEMIFY_BUILDER_STYLESHEET::REMOVE_CSS_FILES
 * is the function that drops it (class-themify-builder-stylesheet.php:388-392),
 * and the plugin's own programmatic write path calls exactly this pair in exactly
 * this order (includes/plugin-compat/wpml-translation.php:102-111). So does this.
 *
 * @param list<array<string, mixed>> $rows
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_write(int $post_id, array $rows): array|WP_Error
{
    if (!nibwp_themify_can_write()) {
        return nibwp_themify_err(
            'write_unavailable',
            __(
                'This build of Themify Builder has no sanitised save seam, so builder writes are read-only here. Writing the builder meta directly would mean re-implementing the content escaper, the kses floor, the element-id generator and the plain-text mirror, and builder data stored in the wrong shape renders the page empty.',
                'nibwp'
            ),
            501
        );
    }

    // 'backend' is what the editor's own full save passes
    // (class-themify-builder-active.php:660): it rewrites the static-content
    // mirror and records a revision, which is what makes the write undoable.
    $result = ThemifyBuilder_Data_Manager::save_data($rows, $post_id, 'backend', null, null, []);

    if ($result instanceof WP_Error) {
        return $result;
    }

    if (!is_array($result) || !array_key_exists('mid', $result)) {
        return nibwp_themify_err('write_failed', __('Themify Builder did not report the result of the save.', 'nibwp'), 500);
    }

    if ($result['mid'] === false) {
        return nibwp_themify_err(
            'write_declined',
            __('Themify Builder rolled the save back; the page is unchanged.', 'nibwp'),
            500
        );
    }

    $css_cleared = nibwp_themify_flush_css($post_id);

    return [
        'post_id' => $post_id,
        'written' => true,
        'rows' => count($rows),
        'css_cache_cleared' => $css_cleared,
    ];
}

/**
 * Drop the page's generated stylesheet so the new markup is styled by new CSS.
 *
 * Guarded because the class is loaded conditionally and a missing stylesheet
 * directory makes the filesystem helper throw rather than return.
 */
function nibwp_themify_flush_css(int $post_id): bool
{
    if (!class_exists('Themify_Builder_Stylesheet')
        || !method_exists('Themify_Builder_Stylesheet', 'remove_css_files')) {
        return false;
    }

    try {
        Themify_Builder_Stylesheet::remove_css_files($post_id);
    } catch (\Throwable $error) {
        return false;
    }

    return true;
}

