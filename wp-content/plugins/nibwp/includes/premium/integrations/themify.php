/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_manage(array $input): array|WP_Error
{
    $guard = nibwp_themify_guard();

    if ($guard instanceof WP_Error) {
        return $guard;
    }

    $action = isset($input['action']) && is_scalar($input['action']) ? (string) $input['action'] : '';

    if (!in_array($action, nibwp_themify_actions(), true)) {
        return nibwp_themify_err(
            'unknown_action',
            sprintf(
                /* translators: 1: action name, 2: list of valid actions */
                __('Unknown Themify action "%1$s". Valid actions: %2$s.', 'nibwp'),
                $action,
                implode(', ', nibwp_themify_actions())
            )
        );
    }

    // The plugin's internals are version-sensitive, the save seam runs third-party
    // module sanitisers we do not control, and its filesystem helpers throw on an
    // unwritable uploads directory. One catch turns any of that into a named
    // refusal rather than a fatal that takes the whole REST request with it.
    try {
        return nibwp_themify_dispatch($action, $input);
    } catch (\Throwable $error) {
        return nibwp_themify_err(
            'plugin_error',
            sprintf(
                /* translators: 1: action name, 2: error message from the plugin */
                __('Themify Builder could not complete %1$s: %2$s', 'nibwp'),
                $action,
                $error->getMessage()
            ),
            500
        );
    }
}

