/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_add_column(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $rows = $resolved['rows'];
    $located = nibwp_themify_locate_row($rows, $input);

    if ($located instanceof WP_Error) {
        return $located;
    }

    $row = $located['element'];
    $existing = nibwp_themify_cols($row);

    if (count($existing) >= 6) {
        return nibwp_themify_err('row_full', __('A row holds at most 6 columns.', 'nibwp'));
    }

    $column = [
        'element_id' => nibwp_themify_unique_id($rows, 'col'),
        'grid_class' => nibwp_themify_equal_grid(count($existing) + 1),
        'modules' => [],
    ];

    $list = $existing;
    $position = nibwp_themify_int($input['position'] ?? null);
    $at = $position === null ? count($list) : max(0, min($position, count($list)));
    array_splice($list, $at, 0, [$column]);

    // The new split applies to every column in the row, not just the new one.
    $grid = nibwp_themify_equal_grid(count($list));

    foreach ($list as $i => $entry) {
        $entry['grid_class'] = $grid;
        $list[$i] = $entry;
    }

    $row['cols'] = $list;

    if (!nibwp_themify_replace_at($rows, $located['path'], $row)) {
        return nibwp_themify_err('update_failed', __('That row could not be updated.', 'nibwp'), 500);
    }

    $written = nibwp_themify_write((int) $resolved['post']->ID, $rows);

    if ($written instanceof WP_Error) {
        return $written;
    }

    return $written + [
        'column' => $at,
        'element_id' => (string) $column['element_id'],
        'columns' => count($list),
        'grid_class' => $grid,
    ];
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_remove_column(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $rows = $resolved['rows'];
    $located = nibwp_themify_locate_column($rows, $input);

    if ($located instanceof WP_Error) {
        return $located;
    }

    $removed_id = nibwp_themify_element_id($located['element']);
    $modules = count(nibwp_themify_modules($located['element']));

    if ($modules > 0 && (!isset($input['merge']) || $input['merge'] !== false)) {
        // Removing a column takes its modules with it. That is a page losing
        // content, so it has to be asked for rather than assumed.
        return nibwp_themify_err('column_not_empty', sprintf(
            /* translators: %d: number of modules */
            __('That column still holds %d module(s). Move or remove them first, or pass merge=false to delete the column and its modules together.', 'nibwp'),
            $modules
        ));
    }

    if (!nibwp_themify_remove_at($rows, $located['path'])) {
        return nibwp_themify_err('remove_failed', __('That column could not be removed.', 'nibwp'), 500);
    }

    // Re-split whatever is left, so the row does not render with a gap.
    $row_path = array_slice($located['path'], 0, count($located['path']) - 2);
    $parent = nibwp_themify_at($rows, $row_path);

    if (is_array($parent)) {
        $list = nibwp_themify_cols($parent);

        if ($list !== []) {
            $grid = nibwp_themify_equal_grid(count($list));

            foreach ($list as $i => $entry) {
                $entry['grid_class'] = $grid;
                $list[$i] = $entry;
            }

            $parent['cols'] = $list;
            nibwp_themify_replace_at($rows, $row_path, $parent);
        }
    }

    $written = nibwp_themify_write((int) $resolved['post']->ID, $rows);

    if ($written instanceof WP_Error) {
        return $written;
    }

    return $written + ['removed' => $removed_id, 'modules_removed' => $modules];
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_set_column_widths(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $rows = $resolved['rows'];
    $located = nibwp_themify_locate_row($rows, $input);

    if ($located instanceof WP_Error) {
        return $located;
    }

    $widths = $input['widths'] ?? null;

    if (!is_array($widths) || $widths === []) {
        return nibwp_themify_err('bad_widths', __('widths must be a list of Themify grid classes.', 'nibwp'));
    }

    $allowed = nibwp_themify_grid_classes();
    $clean = [];

    foreach ($widths as $width) {
        if (!is_scalar($width) || !in_array((string) $width, $allowed, true)) {
            return nibwp_themify_err('bad_widths', sprintf(
                /* translators: %s: list of valid grid classes */
                __('A column width must be one of: %s.', 'nibwp'),
                implode(', ', $allowed)
            ));
        }

        $clean[] = (string) $width;
    }

    $row = $located['element'];
    $list = nibwp_themify_cols($row);

    if (count($clean) !== count($list)) {
        return nibwp_themify_err('width_count', sprintf(
            /* translators: 1: widths given, 2: columns in the row */
            __('%1$d width(s) given for a row with %2$d column(s).', 'nibwp'),
            count($clean),
            count($list)
        ));
    }

    foreach ($list as $i => $entry) {
        $entry['grid_class'] = $clean[$i];
        $list[$i] = $entry;
    }

    $row['cols'] = $list;

    if (!nibwp_themify_replace_at($rows, $located['path'], $row)) {
        return nibwp_themify_err('update_failed', __('That row could not be updated.', 'nibwp'), 500);
    }

    $written = nibwp_themify_write((int) $resolved['post']->ID, $rows);

    if ($written instanceof WP_Error) {
        return $written;
    }

    return $written + ['widths' => $clean];
}

