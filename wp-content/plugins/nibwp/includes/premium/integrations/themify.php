/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_list_module_types(array $input): array|WP_Error
{
    if ($denied = nibwp_themify_require_author(__('Listing the builder module types', 'nibwp'))) {
        return $denied;
    }

    $limit = nibwp_themify_limit($input['limit'] ?? null);
    $offset = isset($input['offset']) && is_scalar($input['offset']) ? max(0, (int) $input['offset']) : 0;
    $all = nibwp_themify_module_registry('all');
    $active = nibwp_themify_module_registry('active');
    $names = array_keys($all);
    sort($names);
    $slice = array_slice($names, $offset, $limit);
    $types = [];

    foreach ($slice as $name) {
        $types[] = [
            'mod_name' => (string) $name,
            // A type can be registered and still switched off in the builder
            // settings, in which case existing modules of it stop rendering
            // (class-themify-builder-model.php:478-487).
            'enabled' => isset($active[$name]),
        ];
    }

    return [
        'types' => $types,
        'total' => count($names),
        'enabled' => count($active),
        'limit' => $limit,
        'offset' => $offset,
        'truncated' => count($names) > ($offset + count($slice)),
    ];
}

