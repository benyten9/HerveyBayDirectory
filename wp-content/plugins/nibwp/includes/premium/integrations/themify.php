/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_reorder_rows(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $rows = $resolved['rows'];
    $order = $input['order'] ?? null;

    if (!is_array($order)) {
        return nibwp_themify_err('bad_order', __('order must be a list of row indexes.', 'nibwp'));
    }

    $wanted = [];

    foreach ($order as $entry) {
        if (!is_scalar($entry)) {
            return nibwp_themify_err('bad_order', __('order must be a list of row indexes.', 'nibwp'));
        }

        $wanted[] = (int) $entry;
    }

    // A partial order would silently drop the rows left out of it, which is a
    // page losing sections and reporting success.
    $expected = range(0, count($rows) - 1);
    $sorted = $wanted;
    sort($sorted);

    if (count($rows) === 0 || $sorted !== $expected) {
        return nibwp_themify_err('bad_order', sprintf(
            /* translators: %d: number of rows */
            __('order must list every one of the %d current row indexes exactly once.', 'nibwp'),
            count($rows)
        ));
    }

    $reordered = [];

    foreach ($wanted as $index) {
        $reordered[] = $rows[$index];
    }

    $written = nibwp_themify_write((int) $resolved['post']->ID, $reordered);

    if ($written instanceof WP_Error) {
        return $written;
    }

    return $written + ['order' => $wanted];
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_update_row(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $rows = $resolved['rows'];
    $located = nibwp_themify_locate_row($rows, $input);

    if ($located instanceof WP_Error) {
        return $located;
    }

    $settings = nibwp_themify_clean_settings($input['settings'] ?? null);

    if ($settings instanceof WP_Error) {
        return $settings;
    }

    $row = $located['element'];
    $key = nibwp_themify_settings_key($row);
    $merge = !isset($input['merge']) || $input['merge'] !== false;
    $existing = isset($row[$key]) && is_array($row[$key]) ? $row[$key] : [];
    // Everything outside the settings key — the columns, the element id, whatever
    // else this row carries — is left exactly as it was read.
    $row[$key] = $merge ? $settings + $existing : $settings;

    if (!nibwp_themify_replace_at($rows, $located['path'], $row)) {
        return nibwp_themify_err('update_failed', __('That row could not be updated.', 'nibwp'), 500);
    }

    $written = nibwp_themify_write((int) $resolved['post']->ID, $rows);

    if ($written instanceof WP_Error) {
        return $written;
    }

    return $written + [
        'element_id' => nibwp_themify_element_id($row),
        'settings_key' => $key,
        'merged' => $merge,
    ];
}

