/* ----------------------------------------------------- the builder's settings */

/**
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_get_settings(): array|WP_Error
{
    if ($denied = nibwp_themify_require_admin(__('Reading the Themify Builder settings', 'nibwp'))) {
        return $denied;
    }

    $stored = get_option(NIBWP_THEMIFY_OPTION, []);
    $stored = is_array($stored) ? $stored : [];
    $allowed = nibwp_themify_public_settings();

    $settings = [];
    $withheld = [];

    foreach ($allowed as $key => $type) {
        if (!array_key_exists($key, $stored)) {
            continue;
        }

        $report = nibwp_themify_report_setting($type, $stored[$key]);

        if (array_key_exists('value', $report)) {
            $settings[$key] = $report['value'];

            continue;
        }

        $withheld[] = ['key' => $key, 'is_set' => true, 'reason' => 'not_a_scalar'];
    }

    foreach ($stored as $key => $value) {
        $key = (string) $key;

        if (isset($allowed[$key])) {
            continue;
        }

        // Name and whether it is set, and nothing else. themify_builder_setting is
        // one flat bag every add-on writes into, so a key nobody has vouched for
        // could be anything, including somebody's licence key.
        $withheld[] = [
            'key' => $key,
            'is_set' => $value !== '' && $value !== null && $value !== false,
            'reason' => 'not_allow_listed',
        ];
    }

    return [
        'option' => NIBWP_THEMIFY_OPTION,
        'settings' => $settings,
        'withheld' => $withheld,
        'allow_listed' => array_keys($allowed),
        'note' => __('Values are reported for an allow-listed set of layout and performance switches. Everything else is reported as a name and whether it is set.', 'nibwp'),
    ];
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_update_settings(array $input): array|WP_Error
{
    if ($denied = nibwp_themify_require_admin(__('Changing the Themify Builder settings', 'nibwp'))) {
        return $denied;
    }

    $patch = $input['settings_update'] ?? null;

    if (!is_array($patch) || $patch === []) {
        return nibwp_themify_err('bad_settings_update', __('settings_update must be an object of allow-listed setting names and values.', 'nibwp'));
    }

    $allowed = nibwp_themify_public_settings();
    $stored = get_option(NIBWP_THEMIFY_OPTION, []);
    $stored = is_array($stored) ? $stored : [];
    $before = $stored;

    $changed = [];
    $refused = [];

    foreach ($patch as $key => $value) {
        $key = (string) $key;

        if (!isset($allowed[$key])) {
            $refused[] = $key;

            continue;
        }

        if (!is_scalar($value)) {
            $refused[] = $key;

            continue;
        }

        $stored[$key] = match ($allowed[$key]) {
            'int' => (int) $value,
            'bool' => $value ? '1' : '',
            default => sanitize_text_field((string) $value),
        };
        $changed[] = $key;
    }

    if ($changed === []) {
        return nibwp_themify_err(
            'nothing_written',
            sprintf(
                /* translators: %s: list of refused keys */
                __('Nothing in settings_update is writable here. Refused: %s.', 'nibwp'),
                implode(', ', $refused)
            )
        );
    }

    update_option(NIBWP_THEMIFY_OPTION, $stored, false);

    // A breakpoint change invalidates every generated stylesheet on the site, and
    // the builder's own settings page regenerates them for exactly this reason
    // (plugin/classes/class-themify-builder-settings.php:75-80).
    $css_regenerated = false;

    foreach (['tablet_landscape', 'tablet', 'mobile'] as $breakpoint) {
        $key = 'builder_responsive_design_' . $breakpoint;

        if (in_array($key, $changed, true) && ($before[$key] ?? null) !== $stored[$key]) {
            $css_regenerated = nibwp_themify_regenerate_css();

            break;
        }
    }

    return [
        'option' => NIBWP_THEMIFY_OPTION,
        'changed' => $changed,
        'refused' => $refused,
        'css_regenerated' => $css_regenerated,
    ];
}

/** Drop every generated stylesheet, guarded because it touches the filesystem. */
function nibwp_themify_regenerate_css(): bool
{
    if (!class_exists('Themify_Builder_Stylesheet')
        || !method_exists('Themify_Builder_Stylesheet', 'regenerate_css_files')) {
        return false;
    }

    try {
        Themify_Builder_Stylesheet::regenerate_css_files('');
    } catch (\Throwable $error) {
        return false;
    }

    return true;
}

/* --------------------------------------------------------------------- audits */

/** The checks `audit` runs, and what each one is looking for. */
function nibwp_themify_checks(): array
{
    return ['missing_modules', 'empty_containers', 'stale_cache', 'dead_layout_parts'];
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_audit(array $input): array|WP_Error
{
    $wanted = isset($input['check']) && is_scalar($input['check']) ? sanitize_key((string) $input['check']) : '';

    if ($wanted !== '' && !in_array($wanted, nibwp_themify_checks(), true)) {
        return nibwp_themify_err('bad_check', sprintf(
            /* translators: %s: list of check names */
            __('check must be one of: %s.', 'nibwp'),
            implode(', ', nibwp_themify_checks())
        ));
    }

    $checks = $wanted === '' ? nibwp_themify_checks() : [$wanted];
    $found = nibwp_themify_find_pages($input);

    if ($found instanceof WP_Error) {
        return $found;
    }

    $report = [];
    $total = 0;

    foreach ($checks as $check) {
        $findings = match ($check) {
            'missing_modules' => nibwp_themify_check_missing_modules($found['ids']),
            'empty_containers' => nibwp_themify_check_empty_containers($found['ids']),
            'stale_cache' => nibwp_themify_check_stale_cache($found['ids']),
            default => nibwp_themify_check_dead_layout_parts($input),
        };

        $report[$check] = $findings;
        $total += count($findings);
    }

    return [
        'checks' => array_keys($report),
        'findings' => $report,
        'total_findings' => $total,
        'pages_scanned' => count($found['ids']),
        'candidates' => $found['candidates'],
        'skipped_no_permission' => $found['skipped_no_permission'],
        'limit' => $found['limit'],
        'offset' => $found['offset'],
        'truncated' => $found['truncated'],
    ];
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_audit_missing_modules(array $input): array|WP_Error
{
    $found = nibwp_themify_find_pages($input);

    if ($found instanceof WP_Error) {
        return $found;
    }

    $findings = nibwp_themify_check_missing_modules($found['ids']);

    return [
        'findings' => $findings,
        'total_findings' => count($findings),
        'pages_scanned' => count($found['ids']),
        'candidates' => $found['candidates'],
        'skipped_no_permission' => $found['skipped_no_permission'],
        'limit' => $found['limit'],
        'offset' => $found['offset'],
        'truncated' => $found['truncated'],
        'note' => __('A module whose type is no longer registered renders nothing. The page still holds its content, so switching the module type back on, or reinstalling whatever supplied it, restores the section.', 'nibwp'),
    ];
}

/**
 * Modules whose type nothing registers any more.
 *
 * This is the commonest "my section vanished": the content is still in the meta,
 * the renderer has nothing to render it with, and the page comes out short.
 *
 * @param list<int> $ids
 * @return list<array<string, mixed>>
 */
function nibwp_themify_check_missing_modules(array $ids): array
{
    $registry = nibwp_themify_module_registry('all');
    $active = nibwp_themify_module_registry('active');
    $findings = [];

    foreach ($ids as $id) {
        $rows = nibwp_themify_read_builder($id);

        if ($rows === null) {
            continue;
        }

        foreach (nibwp_themify_flat_modules($rows) as $entry) {
            if ($entry['mod_name'] === '') {
                // A sub-row has no type of its own; anything else without one is a
                // module the editor cannot open either.
                if (!nibwp_themify_is_subrow($entry['module'])) {
                    $findings[] = [
                        'post_id' => $id,
                        'element_id' => $entry['element_id'],
                        'mod_name' => '',
                        'problem' => 'no_mod_name',
                        'depth' => $entry['depth'],
                    ];
                }

                continue;
            }

            if (!isset($registry[$entry['mod_name']])) {
                $findings[] = [
                    'post_id' => $id,
                    'element_id' => $entry['element_id'],
                    'mod_name' => $entry['mod_name'],
                    'problem' => 'type_not_registered',
                    'depth' => $entry['depth'],
                ];

                continue;
            }

            if (!isset($active[$entry['mod_name']])) {
                $findings[] = [
                    'post_id' => $id,
                    'element_id' => $entry['element_id'],
                    'mod_name' => $entry['mod_name'],
                    'problem' => 'type_disabled_in_settings',
                    'depth' => $entry['depth'],
                ];
            }
        }
    }

    return $findings;
}

/**
 * Rows and columns holding nothing.
 *
 * Harmless on their own, and the reason a page has a band of empty space nobody
 * can click on in the editor.
 *
 * @param list<int> $ids
 * @return list<array<string, mixed>>
 */
function nibwp_themify_check_empty_containers(array $ids): array
{
    $findings = [];

    foreach ($ids as $id) {
        $rows = nibwp_themify_read_builder($id);

        if ($rows === null) {
            continue;
        }

        foreach ($rows as $ri => $row) {
            // Stored keys, not re-keyed ones: a finding names a position a caller
            // is going to address, so the two have to be the same number.
            $cols = nibwp_themify_col_entries($row);

            if ($cols === []) {
                $findings[] = [
                    'post_id' => $id,
                    'element_id' => nibwp_themify_element_id($row),
                    'kind' => 'row',
                    'row' => $ri,
                    'problem' => 'row_has_no_columns',
                ];

                continue;
            }

            $modules = 0;

            foreach ($cols as $ci => $col) {
                $in_col = count(nibwp_themify_modules($col));
                $modules += $in_col;

                if ($in_col === 0) {
                    $findings[] = [
                        'post_id' => $id,
                        'element_id' => nibwp_themify_element_id($col),
                        'kind' => 'column',
                        'row' => $ri,
                        'column' => $ci,
                        'problem' => 'column_has_no_modules',
                    ];
                }
            }

            if ($modules === 0) {
                $findings[] = [
                    'post_id' => $id,
                    'element_id' => nibwp_themify_element_id($row),
                    'kind' => 'row',
                    'row' => $ri,
                    'problem' => 'row_has_no_modules',
                ];
            }
        }
    }

    return $findings;
}

/**
 * Pages whose cached copies of the builder content have gone stale.
 *
 * Two faults, both of which make a page behave as though an old version of it is
 * still live:
 *
 *   - THE PLAIN-TEXT MIRROR. Themify keeps a text copy of the builder content in
 *     post_content between <!--themify_builder_static--> markers
 *     (class-builder-data-manager.php:350-394). Search, excerpts and themes that
 *     bypass the builder read that, not the meta. A builder page without one, or
 *     with an empty one, is a page that does not come up in its own site search.
 *   - THE UNMIGRATED LEGACY ROW. A page still holding _themify_builder_settings
 *     makes the plugin migrate and WRITE on the next cold read
 *     (class-builder-data-manager.php:72-76), so the page is one read away from
 *     changing underneath whoever is editing it.
 *
 * @param list<int> $ids
 * @return list<array<string, mixed>>
 */
function nibwp_themify_check_stale_cache(array $ids): array
{
    $findings = [];

    foreach ($ids as $id) {
        $rows = nibwp_themify_read_builder($id);

        if ($rows === null) {
            continue;
        }

        $storage = nibwp_themify_storage($id);

        if ($storage !== 'json') {
            $findings[] = [
                'post_id' => $id,
                'problem' => 'legacy_meta_not_migrated',
                'storage' => $storage,
            ];
        }

        $post = get_post($id);
        $content = is_object($post) && isset($post->post_content) && is_scalar($post->post_content)
            ? (string) $post->post_content
            : '';
        $tally = nibwp_themify_tally($rows);

        if ($tally['modules'] === 0) {
            continue;
        }

        if (!str_contains($content, NIBWP_THEMIFY_STATIC_OPEN)) {
            $findings[] = [
                'post_id' => $id,
                'problem' => 'static_mirror_missing',
                'modules' => $tally['modules'],
            ];

            continue;
        }

        if (trim(str_replace([NIBWP_THEMIFY_STATIC_OPEN, '<!--/themify_builder_static-->'], '', $content)) === '') {
            $findings[] = [
                'post_id' => $id,
                'problem' => 'static_mirror_empty',
                'modules' => $tally['modules'],
            ];
        }
    }

    return $findings;
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_audit_dead_layout_parts(array $input): array|WP_Error
{
    if ($denied = nibwp_themify_require_author(__('Auditing the builder layout parts', 'nibwp'))) {
        return $denied;
    }

    $findings = nibwp_themify_check_dead_layout_parts($input);
    $limit = nibwp_themify_limit($input['limit'] ?? null);
    $offset = isset($input['offset']) && is_scalar($input['offset']) ? max(0, (int) $input['offset']) : 0;

    return [
        'findings' => $findings,
        'total_findings' => count($findings),
        'limit' => $limit,
        'offset' => $offset,
        'truncated' => false,
        'note' => __('A layout part nothing embeds renders nowhere. Themify does not warn about it, because a part is only ever shown by a layout-part module or a [themify_layout_part] shortcode, and neither is required to exist.', 'nibwp'),
    ];
}

/**
 * Layout parts that nothing on the site embeds, within the scan bound.
 *
 * @param array<string, mixed> $input
 * @return list<array<string, mixed>>
 */
function nibwp_themify_check_dead_layout_parts(array $input): array
{
    if (!function_exists('post_type_exists') || !post_type_exists(NIBWP_THEMIFY_LAYOUT_PART_CPT)) {
        return [];
    }

    $limit = nibwp_themify_limit($input['limit'] ?? null);
    $offset = isset($input['offset']) && is_scalar($input['offset']) ? max(0, (int) $input['offset']) : 0;

    $parts = get_posts([
        'post_type' => NIBWP_THEMIFY_LAYOUT_PART_CPT,
        'post_status' => ['publish', 'draft', 'pending', 'private'],
        'numberposts' => $limit,
        'offset' => $offset,
        'orderby' => 'ID',
        'order' => 'ASC',
        'suppress_filters' => false,
    ]);

    if (!is_array($parts) || $parts === []) {
        return [];
    }

    $findings = [];

    foreach ($parts as $part) {
        if (!is_object($part) || !isset($part->ID)) {
            continue;
        }

        $id = (int) $part->ID;

        if (!current_user_can(NIBWP_THEMIFY_POST_CAP, $id)) {
            continue;
        }

        $slug = isset($part->post_name) && is_scalar($part->post_name) ? (string) $part->post_name : '';
        $usage = nibwp_themify_find_usage($id, $slug, $input);

        if ($usage['sites'] !== []) {
            continue;
        }

        $findings[] = [
            'post_id' => $id,
            'title' => isset($part->post_title) && is_scalar($part->post_title) ? (string) $part->post_title : '',
            'slug' => $slug,
            'status' => isset($part->post_status) && is_scalar($part->post_status) ? (string) $part->post_status : '',
            'problem' => 'nothing_embeds_it',
            'pages_scanned' => $usage['scanned'],
            'scan_truncated' => $usage['truncated'],
        ];
    }

    return $findings;
}
