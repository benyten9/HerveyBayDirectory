/**
 * Find a row, by element_id or by index.
 *
 * @param list<array<string, mixed>> $rows
 * @param array<string, mixed> $input
 * @return array{path: list<int|string>, element: array<string, mixed>}|WP_Error
 */
function nibwp_themify_locate_row(array $rows, array $input): array|WP_Error
{
    $element_id = isset($input['element_id']) && is_scalar($input['element_id'])
        ? (string) $input['element_id']
        : '';

    if ($element_id !== '') {
        $path = nibwp_themify_find_path($rows, $element_id);

        if ($path === null) {
            return nibwp_themify_err('element_not_found', sprintf(
                /* translators: %s: element id */
                __('No element "%s" is in this page.', 'nibwp'),
                $element_id
            ), 404);
        }

        if (count($path) !== 1) {
            return nibwp_themify_err('not_a_row', sprintf(
                /* translators: %s: element id */
                __('Element "%s" is not a top-level row.', 'nibwp'),
                $element_id
            ));
        }

        return ['path' => $path, 'element' => nibwp_themify_at($rows, $path) ?? []];
    }

    $index = nibwp_themify_int($input['row'] ?? null);

    if ($index === null) {
        return nibwp_themify_err('bad_row', __('A row index or an element_id is required.', 'nibwp'));
    }

    if (!isset($rows[$index])) {
        return nibwp_themify_err('row_not_found', sprintf(
            /* translators: %d: row index */
            __('This page has no row %d.', 'nibwp'),
            $index
        ), 404);
    }

    return ['path' => [$index], 'element' => $rows[$index]];
}

/**
 * Find a column, by element_id or by row plus column index.
 *
 * @param list<array<string, mixed>> $rows
 * @param array<string, mixed> $input
 * @return array{path: list<int|string>, element: array<string, mixed>}|WP_Error
 */
function nibwp_themify_locate_column(array $rows, array $input, string $id_key = 'element_id', string $row_key = 'row', string $col_key = 'column'): array|WP_Error
{
    $element_id = isset($input[$id_key]) && is_scalar($input[$id_key]) ? (string) $input[$id_key] : '';

    if ($element_id !== '') {
        $path = nibwp_themify_find_path($rows, $element_id);

        if ($path === null) {
            return nibwp_themify_err('element_not_found', sprintf(
                /* translators: %s: element id */
                __('No element "%s" is in this page.', 'nibwp'),
                $element_id
            ), 404);
        }

        if (count($path) < 2 || $path[count($path) - 2] !== 'cols') {
            return nibwp_themify_err('not_a_column', sprintf(
                /* translators: %s: element id */
                __('Element "%s" is not a column.', 'nibwp'),
                $element_id
            ));
        }

        return ['path' => $path, 'element' => nibwp_themify_at($rows, $path) ?? []];
    }

    $row = nibwp_themify_int($input[$row_key] ?? null);
    $column = nibwp_themify_int($input[$col_key] ?? null);

    if ($row === null || $column === null) {
        return nibwp_themify_err('bad_column', __('A row and column index, or a column element_id, is required.', 'nibwp'));
    }

    $path = [$row, 'cols', $column];
    $element = nibwp_themify_at($rows, $path);

    if ($element === null) {
        return nibwp_themify_err('column_not_found', sprintf(
            /* translators: 1: row index, 2: column index */
            __('This page has no column %2$d in row %1$d.', 'nibwp'),
            $row,
            $column
        ), 404);
    }

    return ['path' => $path, 'element' => $element];
}

/**
 * Find a module, by element_id or by row/column/index.
 *
 * @param list<array<string, mixed>> $rows
 * @param array<string, mixed> $input
 * @return array{path: list<int|string>, element: array<string, mixed>}|WP_Error
 */
function nibwp_themify_locate_module(array $rows, array $input): array|WP_Error
{
    $element_id = isset($input['element_id']) && is_scalar($input['element_id'])
        ? (string) $input['element_id']
        : '';

    if ($element_id !== '') {
        $path = nibwp_themify_find_path($rows, $element_id);

        if ($path === null) {
            return nibwp_themify_err('element_not_found', sprintf(
                /* translators: %s: element id */
                __('No element "%s" is in this page.', 'nibwp'),
                $element_id
            ), 404);
        }

        if (count($path) < 2 || $path[count($path) - 2] !== 'modules') {
            return nibwp_themify_err('not_a_module', sprintf(
                /* translators: %s: element id */
                __('Element "%s" is not a module.', 'nibwp'),
                $element_id
            ));
        }

        return ['path' => $path, 'element' => nibwp_themify_at($rows, $path) ?? []];
    }

    $row = nibwp_themify_int($input['row'] ?? null);
    $column = nibwp_themify_int($input['column'] ?? null);
    $index = nibwp_themify_int($input['index'] ?? null);

    if ($row === null || $column === null || $index === null) {
        return nibwp_themify_err('bad_module', __('A row, column and index, or a module element_id, is required.', 'nibwp'));
    }

    $path = [$row, 'cols', $column, 'modules', $index];
    $element = nibwp_themify_at($rows, $path);

    if ($element === null) {
