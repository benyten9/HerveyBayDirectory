            $row,
            $column,
            $index
        ), 404);
    }

    return ['path' => $path, 'element' => $element];
}

/**
 * Settings from a caller, with the entries nothing can store removed.
 *
 * Only scalars, and arrays of scalars one level deep, are kept: the builder's own
 * escaper walks nested arrays and re-decodes nested JSON, and handing it an
 * object or a resource is how a save throws halfway through a transaction.
 *
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_clean_settings(mixed $raw): array|WP_Error
{
    if (!is_array($raw)) {
        return nibwp_themify_err('bad_settings', __('settings must be an object of name/value pairs.', 'nibwp'));
    }

    $clean = [];

    foreach ($raw as $key => $value) {
        $key = (string) $key;

        if ($key === '') {
            continue;
        }

        if (is_scalar($value) || $value === null) {
            $clean[$key] = $value;

            continue;
        }

        if (is_array($value)) {
            $clean[$key] = nibwp_themify_clean_nested($value);
        }
    }

    return $clean;
}

/** @return array<string|int, mixed> */
function nibwp_themify_clean_nested(array $value, int $depth = 0): array
{
    $out = [];

    foreach ($value as $key => $entry) {
        if (is_scalar($entry) || $entry === null) {
            $out[$key] = $entry;

            continue;
        }

        if (is_array($entry) && $depth < 4) {
            $out[$key] = nibwp_themify_clean_nested($entry, $depth + 1);
        }
    }

    return $out;
}

/* ------------------------------------------------------------- row transforms */

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_add_row(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $rows = $resolved['rows'];
    $post_id = (int) $resolved['post']->ID;
    $columns = nibwp_themify_int($input['columns'] ?? null) ?? 1;

    if ($columns < 1 || $columns > 6) {
        return nibwp_themify_err('bad_columns', __('A row has between 1 and 6 columns.', 'nibwp'));
    }

    $grid = nibwp_themify_equal_grid($columns);
    $cols = [];

    for ($i = 0; $i < $columns; $i++) {
        $cols[] = [
            'element_id' => nibwp_themify_unique_id($rows, 'col'),
            'grid_class' => $grid,
            // An empty list, not a missing key: the writer discards the whole
            // payload unless the encoded JSON contains the word 'modules' or
            // 'styling' (class-builder-data-manager.php:471-473).
            'modules' => [],
        ];
    }

    $row = [
        'element_id' => nibwp_themify_unique_id($rows, 'row'),
        'cols' => $cols,
        'styling' => [],
    ];

    $position = nibwp_themify_int($input['position'] ?? null);
    $at = $position === null ? count($rows) : max(0, min($position, count($rows)));
    array_splice($rows, $at, 0, [$row]);

    $written = nibwp_themify_write($post_id, $rows);

    if ($written instanceof WP_Error) {
        return $written;
    }

    return $written + ['row' => $at, 'element_id' => (string) $row['element_id'], 'columns' => $columns];
}

