        default => nibwp_themify_err('unhandled_action', __('Unhandled action.', 'nibwp')),
    };

    return $result instanceof WP_Error ? $result : ['action' => $action] + $result;
}

/* ------------------------------------------------------- finding the pages */

/**
 * Post ids that have builder data, bounded, with the ones this account cannot
 * edit left out and counted.
 *
 * A silently shortened list is one an agent will describe as the whole site, so
 * the count travels with it.
 *
 * Both meta keys are matched, because a page still on the legacy row is a builder
 * page and leaving it out is how an audit misses the pages that need it most.
 *
 * @param array<string, mixed> $input
 * @return array{ids: list<int>, candidates: int, skipped_no_permission: int, limit: int, offset: int, truncated: bool}|WP_Error
 */
function nibwp_themify_find_pages(array $input): array|WP_Error
{
    global $wpdb;

    if (!is_object($wpdb) || !method_exists($wpdb, 'get_col') || !method_exists($wpdb, 'prepare')) {
        return nibwp_themify_err('no_db', __('No database handle is available.', 'nibwp'), 500);
    }

    $limit = nibwp_themify_limit($input['limit'] ?? null);
    $offset = isset($input['offset']) && is_scalar($input['offset']) ? max(0, (int) $input['offset']) : 0;
    $post_type = isset($input['post_type']) && is_scalar($input['post_type'])
        ? sanitize_key((string) $input['post_type'])
        : '';

    // Table names come off $wpdb, never from input. Every value is a placeholder.
    $sql = 'SELECT DISTINCT pm.post_id FROM ' . $wpdb->postmeta . ' pm'
        . ' INNER JOIN ' . $wpdb->posts . ' p ON p.ID = pm.post_id'
        . ' WHERE pm.meta_key IN (%s, %s)'
        . " AND pm.meta_value <> ''"
        . " AND p.post_type <> 'revision'"
        . " AND p.post_status NOT IN ('trash', 'auto-draft', 'inherit')";

    $args = [NIBWP_THEMIFY_META, NIBWP_THEMIFY_LEGACY_META];

    if ($post_type !== '') {
        $sql .= ' AND p.post_type = %s';
        $args[] = $post_type;
    }

    $sql .= ' ORDER BY pm.post_id ASC LIMIT %d OFFSET %d';
    // One more than asked for, so truncation is a fact rather than a guess.
    $args[] = $limit + 1;
    $args[] = $offset;

    $rows = (array) $wpdb->get_col($wpdb->prepare($sql, $args));

    $truncated = count($rows) > $limit;

    if ($truncated) {
        array_pop($rows);
    }

    $ids = [];
    $skipped = 0;

    foreach ($rows as $row) {
        $id = (int) $row;

        if ($id <= 0) {
            continue;
        }

        if (!current_user_can(NIBWP_THEMIFY_POST_CAP, $id)) {
            $skipped++;

            continue;
        }

        $ids[] = $id;
    }

    return [
        'ids' => $ids,
        'candidates' => count($rows),
        'skipped_no_permission' => $skipped,
        'limit' => $limit,
        'offset' => $offset,
        'truncated' => $truncated,
    ];
}

/** Count rows, columns and modules at every depth. */
function nibwp_themify_tally(array $rows): array
{
    $tally = ['rows' => 0, 'columns' => 0, 'modules' => 0, 'subrows' => 0];

    foreach ($rows as $row) {
        if (!is_array($row)) {
            continue;
        }

        $tally['rows']++;

        foreach (nibwp_themify_cols($row) as $col) {
            $tally['columns']++;

            foreach (nibwp_themify_modules($col) as $module) {
                if (nibwp_themify_is_subrow($module)) {
                    $tally['subrows']++;

                    foreach (nibwp_themify_cols($module) as $sub_col) {
                        $tally['columns']++;
                        $tally['modules'] += count(nibwp_themify_modules($sub_col));
                    }

                    continue;
                }

                $tally['modules']++;
            }
        }
    }

    return $tally;
}

/**
 * @param array<string, mixed> $container
 * @return list<array<string, mixed>>
 */
function nibwp_themify_cols(array $container): array
{
    if (!isset($container['cols']) || !is_array($container['cols'])) {
        return [];
    }

    $cols = [];

    foreach (array_values($container['cols']) as $col) {
        if (is_array($col)) {
            $cols[] = $col;
        }
    }

    return $cols;
}

/**
 * The columns of a container, KEEPING their stored keys.
 *
 * nibwp_themify_cols() re-keys, which is right for counting and wrong for
 * reporting: a reported column index has to be the index that addresses that
 * column, or a caller reads position 2 and edits position 3.
 *
 * @param array<string, mixed> $container
 * @return array<int|string, array<string, mixed>>
 */
function nibwp_themify_col_entries(array $container): array
{
    if (!isset($container['cols']) || !is_array($container['cols'])) {
        return [];
    }

    $cols = [];

    foreach ($container['cols'] as $key => $col) {
        if (is_array($col)) {
            $cols[$key] = $col;
        }
    }

    return $cols;
}

