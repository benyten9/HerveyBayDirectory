/**
 * Layout parts and saved layouts, with what governs where they appear.
 *
 * THE CONDITION MODEL, because it is not where people look for it. A layout part
 * has NO conditions of its own in this build: the post type is registered with
 * nothing but a title and a thumbnail (class-themify-builder-layouts.php:134-147)
 * and the only thing that decides where it shows up is whatever embeds it — a
 * layout-part module, whose `selected_layout_part` setting holds the part's SLUG
 * (templates/template-layout-part.php:18, :39), or the
 * [themify_layout_part id= slug=] shortcode
 * (class-themify-builder-layouts.php:319-338). The display conditions live on
 * that embedding row or module, in its own settings under `display_condition`
 * (class-themify-builder-display-conditions.php:44-98). So this reports the
 * embedding sites, and get_layout reports the conditions on each.
 *
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_list_layout_parts(array $input): array|WP_Error
{
    if ($denied = nibwp_themify_require_author(__('Listing the builder layout parts', 'nibwp'))) {
        return $denied;
    }

    $limit = nibwp_themify_limit($input['limit'] ?? null);
    $offset = isset($input['offset']) && is_scalar($input['offset']) ? max(0, (int) $input['offset']) : 0;
    $requested = isset($input['post_type']) && is_scalar($input['post_type'])
        ? sanitize_key((string) $input['post_type'])
        : '';
    $types = [NIBWP_THEMIFY_LAYOUT_PART_CPT, NIBWP_THEMIFY_LAYOUT_CPT];

    if ($requested !== '') {
        if (!in_array($requested, $types, true)) {
            return nibwp_themify_err('bad_post_type', sprintf(
                /* translators: %s: list of post types */
                __('post_type here must be one of: %s.', 'nibwp'),
                implode(', ', $types)
            ));
        }

        $types = [$requested];
    }

    $registered = [];

    foreach ($types as $type) {
        if (function_exists('post_type_exists') && post_type_exists($type)) {
            $registered[] = $type;
        }
    }

    if ($registered === []) {
        return [
            'items' => [],
            'total' => 0,
            'skipped_no_permission' => 0,
            'limit' => $limit,
            'offset' => $offset,
            'truncated' => false,
            'note' => __('This build registers neither layout parts nor saved layouts.', 'nibwp'),
        ];
    }

    $posts = get_posts([
        'post_type' => $registered,
        'post_status' => ['publish', 'draft', 'pending', 'private'],
        // One more than asked for, so truncation is a fact rather than a guess.
        'numberposts' => $limit + 1,
        'offset' => $offset,
        'orderby' => 'ID',
        'order' => 'ASC',
        'suppress_filters' => false,
    ]);

    $posts = is_array($posts) ? $posts : [];
    $truncated = count($posts) > $limit;

    if ($truncated) {
        array_pop($posts);
    }

    $items = [];
    $skipped = 0;

    foreach ($posts as $post) {
        if (!is_object($post) || !isset($post->ID)) {
            continue;
        }

        $id = (int) $post->ID;

        if (!current_user_can(NIBWP_THEMIFY_POST_CAP, $id)) {
            $skipped++;

            continue;
        }

        $rows = nibwp_themify_read_builder($id);

        $items[] = [
            'post_id' => $id,
            'post_type' => isset($post->post_type) && is_scalar($post->post_type) ? (string) $post->post_type : '',
            'title' => isset($post->post_title) && is_scalar($post->post_title) ? (string) $post->post_title : '',
            'slug' => isset($post->post_name) && is_scalar($post->post_name) ? (string) $post->post_name : '',
            'status' => isset($post->post_status) && is_scalar($post->post_status) ? (string) $post->post_status : '',
            'has_builder_data' => $rows !== null,
            'totals' => $rows === null ? nibwp_themify_tally([]) : nibwp_themify_tally($rows),
        ];
    }

    return [
        'items' => $items,
        'total' => count($items),
        'skipped_no_permission' => $skipped,
        'limit' => $limit,
        'offset' => $offset,
        'truncated' => $truncated,
        'condition_model' => __('A layout part carries no conditions of its own. It appears wherever a layout-part module (settings key selected_layout_part, holding the part slug) or a [themify_layout_part] shortcode embeds it, and the display_condition on that embedding element decides where.', 'nibwp'),
    ];
}

/**
 * One layout part or saved layout, with every place that embeds it.
 *
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_get_layout_part(array $input): array|WP_Error
{
    $post_id = is_scalar($input['post_id'] ?? null) ? (int) $input['post_id'] : 0;

    if ($post_id <= 0) {
        return nibwp_themify_err('bad_post_id', __('A post_id is required.', 'nibwp'));
    }

    // Per-post authority first, before existence or type, for the same reason as
    // everywhere else here.
    if (!current_user_can(NIBWP_THEMIFY_POST_CAP, $post_id)) {
        return nibwp_themify_post_forbidden($post_id);
    }

    $post = get_post($post_id);

    if (!is_object($post) || !isset($post->ID)) {
        return nibwp_themify_err('post_not_found', sprintf(
            /* translators: %d: post ID */
            __('No post %d exists.', 'nibwp'),
            $post_id
        ), 404);
    }

    $type = isset($post->post_type) && is_scalar($post->post_type) ? (string) $post->post_type : '';

    if (!in_array($type, [NIBWP_THEMIFY_LAYOUT_PART_CPT, NIBWP_THEMIFY_LAYOUT_CPT], true)) {
        return nibwp_themify_err('not_a_layout_part', sprintf(
            /* translators: 1: post ID, 2: post type */
            __('Post %1$d is a %2$s, not a Themify layout part or saved layout.', 'nibwp'),
            $post_id,
            $type
        ));
    }

    $rows = nibwp_themify_read_builder($post_id);
    $slug = isset($post->post_name) && is_scalar($post->post_name) ? (string) $post->post_name : '';
    $usage = nibwp_themify_find_usage($post_id, $slug, $input);

    return [
        'post_id' => $post_id,
        'post_type' => $type,
        'title' => isset($post->post_title) && is_scalar($post->post_title) ? (string) $post->post_title : '',
        'slug' => $slug,
        'status' => isset($post->post_status) && is_scalar($post->post_status) ? (string) $post->post_status : '',
        'has_builder_data' => $rows !== null,
        'totals' => $rows === null ? nibwp_themify_tally([]) : nibwp_themify_tally($rows),
        'rows' => $rows === null ? [] : nibwp_themify_structure($rows, nibwp_themify_module_registry('all')),
        'embedded_by' => $usage['sites'],
        'embed_count' => count($usage['sites']),
        'pages_scanned' => $usage['scanned'],
        'skipped_no_permission' => $usage['skipped_no_permission'],
        'scan_truncated' => $usage['truncated'],
    ];
}

/**
 * Every builder element that embeds one layout part, within the scan bound.
 *
 * Two routes to find: a layout-part module naming the part's slug in
 * `selected_layout_part`, and a [themify_layout_part] shortcode in any module
 * setting or in the post content.
 *
 * @param array<string, mixed> $input
 * @return array{sites: list<array<string, mixed>>, scanned: int, skipped_no_permission: int, truncated: bool}
 */
function nibwp_themify_find_usage(int $part_id, string $slug, array $input): array
{
    $found = nibwp_themify_find_pages($input);

    if ($found instanceof WP_Error) {
        return ['sites' => [], 'scanned' => 0, 'skipped_no_permission' => 0, 'truncated' => false];
    }

    $sites = [];

    foreach ($found['ids'] as $id) {
        if ($id === $part_id) {
            continue;
        }

        $rows = nibwp_themify_read_builder($id);

        if ($rows === null) {
            continue;
        }

        foreach (nibwp_themify_flat_modules($rows) as $entry) {
            $settings = nibwp_themify_settings($entry['module']);
            $selected = isset($settings['selected_layout_part']) && is_scalar($settings['selected_layout_part'])
                ? (string) $settings['selected_layout_part']
                : '';
            $by_slug = $slug !== '' && $selected === $slug;
            $by_shortcode = nibwp_themify_mentions_part($settings, $part_id, $slug);

            if (!$by_slug && !$by_shortcode) {
                continue;
            }

            $sites[] = [
                'post_id' => $id,
                'element_id' => $entry['element_id'],
                'mod_name' => $entry['mod_name'],
                'via' => $by_slug ? 'layout_part_module' : 'shortcode',
                'display_conditions' => nibwp_themify_conditions($settings),
            ];
        }
    }

    return [
        'sites' => $sites,
        'scanned' => count($found['ids']),
        'skipped_no_permission' => $found['skipped_no_permission'],
        'truncated' => $found['truncated'],
    ];
}

/**
 * Does any string in these settings carry a themify_layout_part shortcode for
 * this part?
 *
 * @param array<string, mixed> $settings
 */
function nibwp_themify_mentions_part(array $settings, int $part_id, string $slug, int $depth = 0): bool
{
    foreach ($settings as $value) {
        if (is_string($value) && str_contains($value, 'themify_layout_part')) {
            if (str_contains($value, 'id="' . (string) $part_id . '"')
                || ($slug !== '' && str_contains($value, 'slug="' . $slug . '"'))) {
                return true;
            }
        }

        if (is_array($value) && $depth < 4 && nibwp_themify_mentions_part($value, $part_id, $slug, $depth + 1)) {
            return true;
        }
    }

    return false;
}

