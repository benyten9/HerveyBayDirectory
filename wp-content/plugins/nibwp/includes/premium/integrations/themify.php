/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_list_pages(array $input): array|WP_Error
{
    $found = nibwp_themify_find_pages($input);

    if ($found instanceof WP_Error) {
        return $found;
    }

    $pages = [];

    foreach ($found['ids'] as $id) {
        $rows = nibwp_themify_read_builder($id);

        if ($rows === null) {
            continue;
        }

        $post = get_post($id);
        $tally = nibwp_themify_tally($rows);

        $pages[] = [
            'post_id' => $id,
            'title' => is_object($post) && isset($post->post_title) && is_scalar($post->post_title)
                ? (string) $post->post_title
                : '',
            'post_type' => is_object($post) && isset($post->post_type) && is_scalar($post->post_type)
                ? (string) $post->post_type
                : '',
            'status' => is_object($post) && isset($post->post_status) && is_scalar($post->post_status)
                ? (string) $post->post_status
                : '',
            'rows' => $tally['rows'],
            'columns' => $tally['columns'],
            'modules' => $tally['modules'],
            'subrows' => $tally['subrows'],
            'storage' => nibwp_themify_storage($id),
        ];
    }

    return [
        'pages' => $pages,
        'candidates' => $found['candidates'],
        'skipped_no_permission' => $found['skipped_no_permission'],
        'limit' => $found['limit'],
        'offset' => $found['offset'],
        'truncated' => $found['truncated'],
    ];
}

/** Which meta row this page's builder data is actually in. */
function nibwp_themify_storage(int $post_id): string
{
    $json = get_post_meta($post_id, NIBWP_THEMIFY_META, true);

    if ($json !== '' && $json !== null && $json !== false) {
        $legacy = get_post_meta($post_id, NIBWP_THEMIFY_LEGACY_META, true);

        return ($legacy !== '' && $legacy !== null && $legacy !== false) ? 'json+legacy' : 'json';
    }

    return 'legacy';
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_summary(array $input): array|WP_Error
{
    $found = nibwp_themify_find_pages($input);

    if ($found instanceof WP_Error) {
        return $found;
    }

    $registry = nibwp_themify_module_registry('all');
    $active = nibwp_themify_module_registry('active');
    $types = [];
    $legacy = 0;
    $tally = ['rows' => 0, 'columns' => 0, 'modules' => 0, 'subrows' => 0];

    foreach ($found['ids'] as $id) {
        $rows = nibwp_themify_read_builder($id);

        if ($rows === null) {
            continue;
        }

        if (nibwp_themify_storage($id) !== 'json') {
            $legacy++;
        }

        foreach (nibwp_themify_tally($rows) as $key => $value) {
            $tally[$key] += $value;
        }

        foreach (nibwp_themify_flat_modules($rows) as $entry) {
            $name = $entry['mod_name'];

            if ($name === '') {
                continue;
            }

            $types[$name] = ($types[$name] ?? 0) + 1;
        }
    }

    arsort($types);

    return [
        'version' => defined('THEMIFY_VERSION') ? (string) THEMIFY_VERSION : '',
        'meta_key' => NIBWP_THEMIFY_META,
        'legacy_meta_key' => NIBWP_THEMIFY_LEGACY_META,
        'writable' => nibwp_themify_can_write(),
        'module_types_registered' => count($registry),
        'module_types_enabled' => count($active),
        'builder_pages' => count($found['ids']),
        'pages_on_legacy_meta' => $legacy,
        'totals' => $tally,
        'module_types_in_use' => $types,
        'layout_parts' => nibwp_themify_count_posts(NIBWP_THEMIFY_LAYOUT_PART_CPT),
        'saved_layouts' => nibwp_themify_count_posts(NIBWP_THEMIFY_LAYOUT_CPT),
        'global_styles' => nibwp_themify_count_posts(NIBWP_THEMIFY_GLOBAL_STYLE_CPT),
        'candidates' => $found['candidates'],
        'skipped_no_permission' => $found['skipped_no_permission'],
        'limit' => $found['limit'],
        'offset' => $found['offset'],
        'truncated' => $found['truncated'],
    ];
}

/** How many published-or-draft posts of one of Themify's own types exist. */
function nibwp_themify_count_posts(string $post_type): int
{
    if (!function_exists('post_type_exists') || !post_type_exists($post_type)) {
        return 0;
    }

    $ids = get_posts([
        'post_type' => $post_type,
        'post_status' => ['publish', 'draft', 'pending', 'private'],
        'numberposts' => NIBWP_THEMIFY_MAX_ROWS,
        'fields' => 'ids',
        'suppress_filters' => false,
    ]);

    return is_array($ids) ? count($ids) : 0;
}

/**
 * Every module in a page, flattened, with its path and depth.
 *
 * @param list<array<string, mixed>> $rows
 * @return list<array{element_id: string, mod_name: string, path: list<int|string>, depth: int, module: array<string, mixed>}>
 */
function nibwp_themify_flat_modules(array $rows): array
{
    $out = [];

    foreach ($rows as $ri => $row) {
        if (!is_array($row) || !isset($row['cols']) || !is_array($row['cols'])) {
            continue;
        }

        foreach ($row['cols'] as $ci => $col) {
            if (!is_array($col) || !isset($col['modules']) || !is_array($col['modules'])) {
                continue;
            }

            foreach ($col['modules'] as $mi => $module) {
                if (!is_array($module)) {
                    continue;
                }

                $path = [$ri, 'cols', $ci, 'modules', $mi];

                $out[] = [
                    'element_id' => nibwp_themify_element_id($module),
                    'mod_name' => nibwp_themify_mod_name($module),
                    'path' => $path,
                    'depth' => 1,
                    'module' => $module,
                ];

                if (!nibwp_themify_is_subrow($module)) {
                    continue;
                }

                foreach ($module['cols'] as $sci => $sub_col) {
                    if (!is_array($sub_col) || !isset($sub_col['modules']) || !is_array($sub_col['modules'])) {
                        continue;
                    }

                    foreach ($sub_col['modules'] as $smi => $sub) {
                        if (!is_array($sub)) {
                            continue;
                        }

                        $out[] = [
                            'element_id' => nibwp_themify_element_id($sub),
                            'mod_name' => nibwp_themify_mod_name($sub),
                            'path' => array_merge($path, ['cols', $sci, 'modules', $smi]),
                            'depth' => 2,
                            'module' => $sub,
                        ];
                    }
                }
            }
        }
    }

    return $out;
}

/* ------------------------------------------------------- reading one page */

/**
 * Display conditions on one element, as a readable list.
 *
 * Themify keeps them in the element's own settings under `display_condition`,
 * either as an array or as a JSON string, and the reader accepts both
 * (class-themify-builder-display-conditions.php:52-62). A clause is
 * {general, detail, include}; include:"ex" makes it an exclusion, and an
 * exclusion with no inclusions beside it means "everywhere except"
 * (:73-83).
 *
 * @param array<string, mixed> $settings
 * @return list<array<string, mixed>>
 */
function nibwp_themify_conditions(array $settings): array
{
    if (!isset($settings['display_condition']) || $settings['display_condition'] === '') {
        return [];
    }

    $raw = $settings['display_condition'];

    if (is_string($raw)) {
        $raw = json_decode($raw, true);
    }

    if (!is_array($raw)) {
        return [];
    }

    $out = [];

    foreach ($raw as $clause) {
        if (!is_array($clause) || !isset($clause['general'])) {
            continue;
        }

        $detail = $clause['detail'] ?? 'all';

        $out[] = [
            'general' => is_scalar($clause['general']) ? (string) $clause['general'] : '',
            // A detail can be a nested structure (a role list, a date bag), so it
            // is described rather than cast: (string) on an array is "Array".
            'detail' => is_scalar($detail) ? (string) $detail : '',
            'detail_keys' => is_array($detail) ? array_map('strval', array_keys($detail)) : [],
            'mode' => (isset($clause['include']) && $clause['include'] === 'ex') ? 'exclude' : 'include',
        ];
    }

    return $out;
}

/**
 * One element described for a caller: what it is, not what it stores.
 *
 * @param array<string, mixed> $element
 * @return array<string, mixed>
 */
function nibwp_themify_describe(array $element, string $kind, array $registry): array
{
    $settings = nibwp_themify_settings($element);
    $mod_name = nibwp_themify_mod_name($element);

    $described = [
        'kind' => $kind,
        'element_id' => nibwp_themify_element_id($element),
        'settings_key' => nibwp_themify_settings_key($element),
        'setting_keys' => array_map('strval', array_keys($settings)),
        'display_conditions' => nibwp_themify_conditions($settings),
    ];

    if ($kind === 'module' || $kind === 'subrow') {
        $described['mod_name'] = $mod_name;
        $described['registered'] = $kind === 'subrow' ? true : nibwp_themify_module_registered($mod_name, $registry);
    }

    if ($kind === 'column') {
        $described['grid_class'] = isset($element['grid_class']) && is_scalar($element['grid_class'])
            ? (string) $element['grid_class']
            : '';
    }

    return $described;
}

/**
 * A page's builder data as the nested shape a person sees in the editor.
 *
 * @param list<array<string, mixed>> $rows
 * @return list<array<string, mixed>>
 */
function nibwp_themify_structure(array $rows, array $registry): array
{
    $out = [];

    foreach ($rows as $ri => $row) {
        $described = nibwp_themify_describe($row, 'row', $registry) + ['row' => $ri, 'columns' => []];

        foreach (nibwp_themify_col_entries($row) as $ci => $col) {
            $col_described = nibwp_themify_describe($col, 'column', $registry) + ['column' => $ci, 'modules' => []];

            foreach (nibwp_themify_module_entries($col) as $mi => $module) {
                $is_subrow = nibwp_themify_is_subrow($module);
                $mod_described = nibwp_themify_describe($module, $is_subrow ? 'subrow' : 'module', $registry)
                    + ['index' => $mi];

                if ($is_subrow) {
                    $mod_described['columns'] = [];

                    foreach (nibwp_themify_col_entries($module) as $sci => $sub_col) {
                        $sub_described = nibwp_themify_describe($sub_col, 'column', $registry)
                            + ['column' => $sci, 'modules' => []];

                        foreach (nibwp_themify_module_entries($sub_col) as $smi => $sub) {
                            $sub_described['modules'][] = nibwp_themify_describe($sub, 'module', $registry)
                                + ['index' => $smi];
                        }

                        $mod_described['columns'][] = $sub_described;
                    }
                }

                $col_described['modules'][] = $mod_described;
            }

            $described['columns'][] = $col_described;
        }

        $out[] = $described;
    }

    return $out;
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_get_layout(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $post_id = (int) $resolved['post']->ID;
    $rows = $resolved['rows'];
    $registry = nibwp_themify_module_registry('all');

    return [
        'post_id' => $post_id,
        'writable' => nibwp_themify_can_write(),
        'storage' => nibwp_themify_storage($post_id),
        'totals' => nibwp_themify_tally($rows),
        'rows' => nibwp_themify_structure($rows, $registry),
    ];
}

/**
 * The same page as a short readable tree, for reading rather than editing.
 *
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_layout_outline(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $post_id = (int) $resolved['post']->ID;
    $registry = nibwp_themify_module_registry('all');
    $lines = [];

    foreach (nibwp_themify_structure($resolved['rows'], $registry) as $row) {
        $lines[] = sprintf(
            /* translators: 1: row index, 2: element id, 3: column count, 4: condition note */
            __('Row %1$d (%2$s): %3$d column(s)%4$s', 'nibwp'),
            (int) $row['row'],
            (string) $row['element_id'],
            count($row['columns']),
            nibwp_themify_condition_note($row['display_conditions'])
        );

        foreach ($row['columns'] as $col) {
            $lines[] = sprintf(
                /* translators: 1: column index, 2: grid class, 3: module count */
                __('  Column %1$d [%2$s]: %3$d module(s)', 'nibwp'),
                (int) $col['column'],
                (string) $col['grid_class'],
                count($col['modules'])
            );

            foreach ($col['modules'] as $module) {
                $lines[] = '    ' . nibwp_themify_module_line($module);

                foreach ($module['columns'] ?? [] as $sub_col) {
                    $lines[] = sprintf(
                        /* translators: 1: column index, 2: grid class, 3: module count */
                        __('      Sub-column %1$d [%2$s]: %3$d module(s)', 'nibwp'),
                        (int) $sub_col['column'],
                        (string) $sub_col['grid_class'],
                        count($sub_col['modules'])
                    );

                    foreach ($sub_col['modules'] as $sub) {
                        $lines[] = '        ' . nibwp_themify_module_line($sub);
                    }
                }
            }
        }
    }

    return [
        'post_id' => $post_id,
        'outline' => implode("\n", $lines),
        'lines' => $lines,
        'totals' => nibwp_themify_tally($resolved['rows']),
    ];
}

/** One module as one line of the outline. */
function nibwp_themify_module_line(array $module): string
{
    $suffix = '';

    if (($module['kind'] ?? '') !== 'subrow' && ($module['registered'] ?? true) === false) {
        $suffix = ' ' . __('[TYPE NOT REGISTERED — renders nothing]', 'nibwp');
    }

    return sprintf(
        /* translators: 1: index, 2: module type, 3: element id, 4: warnings */
        __('%1$d. %2$s (%3$s)%4$s', 'nibwp'),
        (int) ($module['index'] ?? 0),
        ($module['kind'] ?? '') === 'subrow' ? 'sub-row' : (string) ($module['mod_name'] ?? ''),
        (string) ($module['element_id'] ?? ''),
        $suffix . nibwp_themify_condition_note($module['display_conditions'] ?? [])
    );
}

/** A one-phrase note about an element's display conditions, '' when it has none. */
function nibwp_themify_condition_note(array $conditions): string
{
    if ($conditions === []) {
        return '';
    }

    $includes = 0;
    $excludes = 0;

    foreach ($conditions as $clause) {
        if (($clause['mode'] ?? '') === 'exclude') {
            $excludes++;

            continue;
        }

        $includes++;
    }

    return ' ' . sprintf(
        /* translators: 1: number of include clauses, 2: number of exclude clauses */
        __('(conditional: %1$d include, %2$d exclude)', 'nibwp'),
        $includes,
        $excludes
    );
}

/**
 * @param array<string, mixed> $input
 * @return array<string, mixed>|WP_Error
 */
function nibwp_themify_list_rows(array $input): array|WP_Error
{
    $resolved = nibwp_themify_resolve($input['post_id'] ?? null);

    if ($resolved instanceof WP_Error) {
        return $resolved;
    }

    $limit = nibwp_themify_limit($input['limit'] ?? null);
    $offset = isset($input['offset']) && is_scalar($input['offset']) ? max(0, (int) $input['offset']) : 0;
    $registry = nibwp_themify_module_registry('all');
    $all = nibwp_themify_structure($resolved['rows'], $registry);
    $slice = array_slice($all, $offset, $limit);
    $rows = [];

    foreach ($slice as $row) {
        $widths = [];
        $modules = 0;

        foreach ($row['columns'] as $col) {
            $widths[] = (string) $col['grid_class'];
            $modules += count($col['modules']);
        }

        $rows[] = [
            'row' => (int) $row['row'],
            'element_id' => (string) $row['element_id'],
            'columns' => count($row['columns']),
            'widths' => $widths,
            'modules' => $modules,
            'display_conditions' => $row['display_conditions'],
            'setting_keys' => $row['setting_keys'],
        ];
    }

    return [
        'post_id' => (int) $resolved['post']->ID,
        'rows' => $rows,
        'total_rows' => count($all),
        'limit' => $limit,
        'offset' => $offset,
        'truncated' => count($all) > ($offset + count($slice)),
    ];
}

